#!/usr/bin/env python3
"""Turn one entry of zk/witness.json into zk/circuit/Prover.toml.

Phase 3 of ZK_REDACTION.md: feed the circuit a real log entry's
template_data and the template_digest the Attester's TPM chain committed
to, so `nargo execute` either reproduces it byte for byte or fails.

    ./zk/gen_prover_toml.py            # entry 0
    ./zk/gen_prover_toml.py 17         # entry 17
    ./zk/gen_prover_toml.py --all      # check every entry is representable

Deliberately does no hashing of its own. If this script recomputed the
digest it would only be testing itself; every value here is copied
verbatim from what the C code produced.
"""

import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
WITNESS = ROOT / "witness.json"
PROVER = ROOT / "circuit" / "Prover.toml"

# Must match sha256_var.nr's MAX_BYTES / MAX_MSG and template.nr's MAX_PATH.
MAX_BYTES = 192
MAX_MSG = 183
MAX_PATH = 136
HEADER_LEN = 47


def path_bytes(p):
    """Recover the n-ng field's raw bytes from the dump's JSON string.

    dump_witness writes printable bytes as themselves and everything else
    as \\u00XX, so every codepoint is <= 255 and latin-1 round-trips it
    exactly. The trailing NUL is part of the field and must survive."""
    return p.encode("latin-1")


def load():
    if not WITNESS.exists():
        sys.exit(
            f"{WITNESS} not found -- run:\n"
            "    make dump_witness && ./bin/dump_witness > zk/witness.json"
        )
    return json.loads(WITNESS.read_text())


def check_all(w):
    """Confirm every entry fits the circuit's fixed bounds before we build
    a circuit around them -- a single oversized entry means MAX_BLOCKS is
    wrong, and it is far cheaper to learn that here."""
    worst = 0
    bad = []
    for e in w["entries"]:
        n = e["template_data_len"]
        worst = max(worst, n)
        if n > MAX_MSG:
            bad.append((e["index"], n))
    print(f"{len(w['entries'])} entries, longest template_data {worst} B "
          f"(MAX_MSG {MAX_MSG})")
    blocks = -(-(worst + 9) // 64)
    print(f"worst-case block count: {blocks}")
    if bad:
        print("TOO LONG for the circuit:")
        for idx, n in bad:
            print(f"  entry {idx}: {n} B")
        sys.exit(1)
    print("all entries fit")


def display_path(p):
    """The n-ng field carries the path *plus* its terminating NUL -- that NUL
    is part of what SHA-256 consumes, so the dump reports it faithfully. It
    must not reach a TOML comment, though: a raw \\x00 there is a parse
    error, not a comment."""
    return "".join(c if c.isprintable() else f"\\x{ord(c):02x}" for c in p)


def emit(w, index):
    entries = w["entries"]
    if index >= len(entries):
        sys.exit(f"entry {index} out of range (have {len(entries)})")
    e = entries[index]

    raw_path = path_bytes(e["path"])
    if len(raw_path) != e["path_len"]:
        sys.exit(
            f"entry {index}: path is {len(raw_path)} B but path_len says "
            f"{e['path_len']} -- bad dump or a non-latin-1 escape"
        )
    if len(raw_path) > MAX_PATH:
        sys.exit(f"entry {index} path is {len(raw_path)} B, over MAX_PATH "
                 f"{MAX_PATH}")

    # The circuit rebuilds template_data itself, so we hand it only the
    # ingredients. Cross-check the length it will derive against the one the
    # C tool recorded -- if these disagree the layout constant is wrong, and
    # that is far easier to read here than as a digest mismatch.
    derived_len = HEADER_LEN + len(raw_path)
    if derived_len != e["template_data_len"]:
        sys.exit(
            f"entry {index}: circuit would build a {derived_len} B record "
            f"but the log's is {e['template_data_len']} B -- HEADER_LEN is "
            "wrong"
        )

    padded_path = list(raw_path) + [0] * (MAX_PATH - len(raw_path))
    file_hash = list(bytes.fromhex(e["file_hash"]))
    digest = list(bytes.fromhex(e["template_digest"]))
    if len(file_hash) != 32:
        sys.exit(f"entry {index}: file_hash is {len(file_hash)} B, not 32")

    def arr(vals):
        return "[" + ", ".join(f'"{v}"' for v in vals) + "]"

    PROVER.write_text(
        f"# Generated by zk/gen_prover_toml.py from zk/witness.json entry "
        f"{index}.\n"
        f"# path: {display_path(e['path'])}\n"
        f"# template_data the circuit will build: {derived_len} B "
        f"({-(-(derived_len + 9) // 64)} SHA-256 blocks)\n\n"
        f"path = {arr(padded_path)}\n"
        f'path_len = "{e["path_len"]}"\n'
        f"file_hash = {arr(file_hash)}\n"
        f"expected_digest = {arr(digest)}\n"
    )
    print(f"wrote {PROVER} for entry {index}")
    print(f"  path              {display_path(e['path'])}")
    print(f"  path_len          {e['path_len']} "
          f"-> template_data {derived_len} B")
    print(f"  file_hash         {e['file_hash']}")
    print(f"  expected_digest   {e['template_digest']}")
    print()
    print("now run:  cd zk/circuit && nargo execute")


def test_salt(i):
    """A deterministic stand-in for a real blinding factor.

    Deterministic on purpose: this is a test harness, and a reproducible
    Prover.toml makes failures reproducible too. THE REAL RP MUST NOT DO
    THIS -- it must draw each salt from a CSPRNG and never reuse one, or
    the commitments become brute-forceable (the space of plausible system
    paths is small) and linkable across attestation runs.

    31 bytes keeps the value below the BN254 field prime unconditionally.
    """
    h = hashlib.sha256(f"charra-zk-test-salt-{i}".encode()).digest()[:31]
    return int.from_bytes(h, "big")


def emit_full(w, tamper=None):
    """Every entry at once, for the whole-log circuit.

    `tamper` deliberately corrupts the witness so we can confirm the
    circuit REJECTS it. A solved witness only shows the circuit accepts the
    truth; it says nothing about whether it would also accept a lie, and a
    trivially-satisfiable assertion would pass just as happily. See
    zk/negative_test.sh.
    """
    entries = w["entries"]

    paths, lens, hashes = [], [], []
    for e in entries:
        raw = path_bytes(e["path"])
        if len(raw) != e["path_len"]:
            sys.exit(f"entry {e['index']}: path/path_len disagree")
        if len(raw) > MAX_PATH:
            sys.exit(f"entry {e['index']}: path {len(raw)} B over MAX_PATH")
        if HEADER_LEN + len(raw) != e["template_data_len"]:
            sys.exit(f"entry {e['index']}: HEADER_LEN wrong")
        if e.get("pcr_index", 10) != 10:
            sys.exit(
                f"entry {e['index']} targets PCR {e['pcr_index']}, not 10. "
                "The circuit replays every entry unconditionally, so a "
                "non-PCR-10 entry would corrupt the chain."
            )
        paths.append(list(raw) + [0] * (MAX_PATH - len(raw)))
        lens.append(e["path_len"])
        hashes.append(list(bytes.fromhex(e["file_hash"])))

    note = ""
    if tamper == "path":
        # Flip one byte of one path: "/usr/..." -> "0usr/...".
        paths[0][0] ^= 0x1f
        note = "TAMPERED: entry 0's first path byte flipped"
    elif tamper == "hash":
        hashes[0][0] ^= 0x01
        note = "TAMPERED: entry 0's file_hash first byte flipped"
    elif tamper == "order":
        if len(entries) < 2:
            sys.exit("need >=2 entries to test reordering")
        paths[0], paths[1] = paths[1], paths[0]
        lens[0], lens[1] = lens[1], lens[0]
        hashes[0], hashes[1] = hashes[1], hashes[0]
        note = "TAMPERED: entries 0 and 1 swapped"
    elif tamper == "drop":
        # Blank the last entry rather than shortening the array -- the
        # circuit's N is fixed, so a real "dropped entry" shows up as one
        # that no longer matches what was measured.
        paths[-1] = [0] * MAX_PATH
        lens[-1] = 0
        note = "TAMPERED: last entry blanked"
    elif tamper is not None:
        sys.exit(f"unknown tamper mode {tamper!r}")

    def arr(vals):
        return "[" + ", ".join(f'"{v}"' for v in vals) + "]"

    def arr2(rows):
        return "[\n" + ",\n".join("  " + arr(r) for r in rows) + "\n]"

    # PCR 0-7 are never extended by an IMA log, so they are still at their
    # power-on value. Emitted as zeros rather than read from anywhere -- if
    # that assumption were wrong the composite would not match, so the
    # circuit passing is itself the check.
    zeros = [[0] * 32 for _ in range(8)]
    salts = [test_salt(i) for i in range(len(entries))]

    PROVER.write_text(
        f"# Generated by zk/gen_prover_toml.py --full from zk/witness.json.\n"
        f"# {len(entries)} entries; PCR 0-7 assumed at power-on (all zero).\n"
        f"# Salts are DETERMINISTIC TEST VALUES -- see test_salt().\n"
        + (f"# {note}\n" if note else "")
        + f"# Target pcrdigest_a: {w['pcrdigest_a']}\n\n"
        f"paths = {arr2(paths)}\n\n"
        f"path_lens = {arr(lens)}\n\n"
        f"salts = {arr(salts)}\n\n"
        f"file_hashes = {arr2(hashes)}\n\n"
        f"other_pcrs = {arr2(zeros)}\n\n"
        f"pcrdigest_a = {arr(list(bytes.fromhex(w['pcrdigest_a'])))}\n"
    )
    if note:
        print(f"wrote {PROVER} -- {note}")
        print("the circuit is EXPECTED to reject this")
        return
    print(f"wrote {PROVER} for all {len(entries)} entries")
    print(f"  pcr10_final   {w['pcr10_final']}")
    print(f"  pcrdigest_a   {w['pcrdigest_a']}")
    print()
    print("now run:  cd zk/circuit && nargo execute")


def main():
    w = load()
    if len(sys.argv) > 1 and sys.argv[1] == "--all":
        check_all(w)
        return
    if len(sys.argv) > 1 and sys.argv[1] == "--full":
        emit_full(w)
        return
    if len(sys.argv) > 1 and sys.argv[1] == "--tamper":
        if len(sys.argv) < 3:
            sys.exit("--tamper needs a mode: path | hash | order | drop")
        emit_full(w, tamper=sys.argv[2])
        return
    index = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    emit(w, index)


if __name__ == "__main__":
    main()
