#!/usr/bin/env python3
"""Emit the Poseidon x5_8 constants as a C header, from Noir's own source.

The C implementation of Poseidon must agree with the circuit's bit for bit,
so the constants are transcribed from the exact file the circuit compiles
against rather than fetched from a reference implementation that is merely
supposed to match. If the library is ever upgraded, re-run this.

Noir's `permute` uses circomlib's optimised form, not the textbook one:
partial rounds use a sparse matrix and the round constants are pre-folded
to suit. That means a naive Poseidon in C would NOT reproduce these
outputs even with the same nominal parameters -- the C code has to mirror
this structure, and these four arrays are what it needs.

    ./zk/extract_poseidon_consts.py > src/core/charra_poseidon_consts.h
"""

import pathlib
import re
import sys

LIB = (pathlib.Path.home()
       / "nargo/github.com/noir-lang/poseidon/v0.3.0"
       / "src/poseidon/bn254/consts.nr")

T = 8            # state width
RF = 8           # full rounds
RP = 64          # partial rounds
N_RC = 128       # round constants, in the optimised layout
N_MDS = T * T
N_SPARSE = RP * (2 * T - 1)      # 64 * 15


def main():
    if not LIB.exists():
        sys.exit(f"{LIB} not found -- run `nargo compile` first to fetch the "
                 "dependency, or fix the path")

    src = LIB.read_text()
    i = src.index("fn x5_8_config")
    # The next definition ends this one. consts.nr uses both `fn` and
    # `pub fn`, so look for either and take whichever comes first -- missing
    # the terminator silently swallows every following config.
    ends = [k for k in (src.find("\nfn ", i + 10),
                        src.find("\npub fn ", i + 10)) if k != -1]
    body = src[i:min(ends)] if ends else src[i:]

    h = re.findall(r"0x[0-9a-fA-F]+", body)
    want = N_RC + N_MDS + N_MDS + N_SPARSE
    if len(h) != want:
        sys.exit(f"expected {want} constants in x5_8_config, found {len(h)}. "
                 "The library layout changed; re-check the slicing before "
                 "trusting anything downstream.")

    rc = h[:N_RC]
    mds = h[N_RC:N_RC + N_MDS]
    pre = h[N_RC + N_MDS:N_RC + 2 * N_MDS]
    sparse = h[N_RC + 2 * N_MDS:]

    def emit(name, vals, per_line=1):
        print(f"static const char* const {name}[] = {{")
        for v in vals:
            print(f'        "{v}",')
        print("};\n")

    print(f"""/* Generated by zk/extract_poseidon_consts.py -- do not edit.
 *
 * Poseidon x5_8 constants for BN254, transcribed from the Noir library the
 * circuit compiles against:
 *   {LIB}
 *
 * t = {T}, full rounds = {RF}, partial rounds = {RP}, alpha = 5.
 *
 * These are the OPTIMISED (circomlib) constants: partial rounds use the
 * sparse matrices below and the round constants are folded to match. A
 * textbook Poseidon using the same nominal parameters will NOT produce the
 * same output -- charra_poseidon.c mirrors Noir's `permute` deliberately.
 */

#ifndef CHARRA_POSEIDON_CONSTS_H
#define CHARRA_POSEIDON_CONSTS_H

#define CHARRA_POSEIDON_T {T}
#define CHARRA_POSEIDON_RF {RF}
#define CHARRA_POSEIDON_RP {RP}
#define CHARRA_POSEIDON_ALPHA 5
#define CHARRA_POSEIDON_N_RC {N_RC}
#define CHARRA_POSEIDON_N_SPARSE {N_SPARSE}

/* BN254 scalar field order. */
static const char* const CHARRA_POSEIDON_P =
        "0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001";
""")
    emit("CHARRA_POSEIDON_RC", rc)
    emit("CHARRA_POSEIDON_MDS", mds)
    emit("CHARRA_POSEIDON_PRESPARSE", pre)
    emit("CHARRA_POSEIDON_SPARSE", sparse)
    print("#endif /* CHARRA_POSEIDON_CONSTS_H */")


if __name__ == "__main__":
    main()
