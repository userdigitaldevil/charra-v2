#!/bin/sh
# Make barretenberg runnable on the Focal (glibc 2.31) dev container.
#
# The problem: every bb release needs a newer glibc than 2.31. The newest,
# 5.0.0-nightly.20260522, needs only 2.34 -- lower than every older release,
# which want 2.38+ -- so it is the one to target.
#
# The approach: fetch glibc and libstdc++ from Ubuntu 22.04 (jammy, glibc
# 2.35) into a PRIVATE sysroot and invoke bb through that loader explicitly.
# The system glibc is not touched, nothing is installed system-wide, and
# removing ~/.bb/sysroot undoes all of it. Upgrading the container's own
# glibc in place would risk every other binary in the image, including the
# TPM simulator; this cannot, because nothing but bb ever sees these libs.
#
# STATUS: this works -- and is NOT sufficient. With the sysroot in place bb
# loads its libraries fine and then dies with SIGILL, because the container
# is x86_64 under Rosetta and Rosetta does not emulate ADX, which
# barretenberg's field arithmetic requires (/proc/cpuinfo shows avx2 and
# bmi2 but no adx). No x86_64 bb binary can run in this container. Kept
# because the sysroot technique is sound and would be needed again if
# charra ever moves to an arm64 Linux container on this glibc.
# See ZK_REDACTION.md section 5.
#
# Run:  ./zk/setup_bb.sh
# Then: ~/.bb/bb-run --version

set -e

BB_VERSION=5.0.0-nightly.20260522
BB_PATH="$HOME/.bb"
SYSROOT="$BB_PATH/sysroot"
POOL=http://archive.ubuntu.com/ubuntu/pool/main

say() { printf '\n== %s\n' "$1"; }

# --- bb itself ---------------------------------------------------------
if [ ! -f "$BB_PATH/bb" ]; then
    say "fetching bb $BB_VERSION"
    mkdir -p "$BB_PATH"
    curl -L --fail \
        "https://github.com/AztecProtocol/barretenberg/releases/download/v${BB_VERSION}/barretenberg-amd64-linux.tar.gz" \
        -o /tmp/bb.tar.gz
    tar xzf /tmp/bb.tar.gz -C "$BB_PATH"
    rm -f /tmp/bb.tar.gz
else
    say "bb already present at $BB_PATH/bb"
fi

# --- jammy runtime into a private sysroot ------------------------------
# Filenames carry point-release suffixes that change, so discover them from
# the pool listing rather than hardcoding a version that will rot.
fetch_deb() {
    dir="$1"
    pattern="$2"
    listing=$(curl -s "$POOL/$dir/")
    file=$(echo "$listing" | grep -o "$pattern" | sort -V | tail -1)
    if [ -z "$file" ]; then
        echo "could not find $pattern in $POOL/$dir/" >&2
        return 1
    fi
    echo "  $file"
    curl -sL --fail "$POOL/$dir/$file" -o "/tmp/$file"
    dpkg-deb -x "/tmp/$file" "$SYSROOT"
    rm -f "/tmp/$file"
}

say "building sysroot from Ubuntu 22.04 packages"
mkdir -p "$SYSROOT"
fetch_deb g/glibc  'libc6_2\.35-[^"]*_amd64\.deb'
fetch_deb g/gcc-12 'libstdc++6_12[^"]*_amd64\.deb'
fetch_deb g/gcc-12 'libgcc-s1_12[^"]*_amd64\.deb'
# bb is OpenMP-threaded; harmless if the system copy already suffices.
fetch_deb l/llvm-toolchain-14 'libomp5-14_14[^"]*_amd64\.deb' || \
    echo "  (libomp not fetched -- only a problem if bb complains about it)"

LOADER="$SYSROOT/lib/x86_64-linux-gnu/ld-linux-x86-64.so.2"
if [ ! -f "$LOADER" ]; then
    echo "loader missing at $LOADER -- sysroot did not build" >&2
    exit 1
fi

# --- wrapper -----------------------------------------------------------
# The sysroot must come FIRST on the library path so its newer glibc wins;
# the system paths follow so bb can still find anything not shipped here.
say "writing wrapper"
cat > "$BB_PATH/bb-run" <<WRAP
#!/bin/sh
# bb, run against the private jammy runtime in $SYSROOT.
# Generated by zk/setup_bb.sh -- see that script for why.
exec "$LOADER" \\
    --library-path "$SYSROOT/lib/x86_64-linux-gnu:$SYSROOT/usr/lib/x86_64-linux-gnu:/lib/x86_64-linux-gnu:/usr/lib/x86_64-linux-gnu" \\
    "$BB_PATH/bb" "\$@"
WRAP
chmod +x "$BB_PATH/bb-run"

say "checking"
if "$BB_PATH/bb-run" --version; then
    printf '\nbb runs. Use ~/.bb/bb-run (not ~/.bb/bb) everywhere.\n'
else
    printf '\nStill failing. Report the error -- if it names a GLIBCXX or a\n'
    printf 'missing .so, that is one more package to add to the sysroot.\n'
    exit 1
fi
