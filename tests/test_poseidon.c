/**
 * @file test_poseidon.c
 * @brief Does the C Poseidon agree with the circuit's?
 *
 * The RP computes each redacted path as Poseidon(path, salt) and the circuit
 * proves that commitment belongs to a path that was really measured. If the
 * two implementations disagree by so much as a bit, every proof fails -- with
 * no diagnostic beyond an unsatisfiable constraint system, which is about the
 * least informative error in the toolchain. This suite is what turns that
 * into a named failure at build time.
 *
 * The vectors are not invented. They are the 33 commitments the circuit
 * itself produced for the real IMA log in zk/witness.json, captured from
 * `nargo execute`, with the exact inputs it was given. If they pass, the two
 * implementations agree on real data.
 *
 * GENERATED -- regenerate if the circuit's hash, its input packing, or the
 * poseidon library version changes. The vectors are only as good as the
 * circuit run they came from.
 *
 * Build and run:  make test_poseidon && ./bin/test_poseidon
 */

