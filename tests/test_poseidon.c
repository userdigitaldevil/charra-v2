#define NUM_VECTORS (sizeof(VECTORS) / sizeof(VECTORS[0]))

static void to_hex(const uint8_t* b, size_t n, char* out) {
    for (size_t i = 0; i < n; i++) {
        sprintf(out + i * 2, "%02x", b[i]);
    }
    out[n * 2] = '\0';
}

/* The check this suite exists for. Reported as one assertion rather than 33,
 * with the first mismatch printed: if the two implementations disagree they
 * disagree on everything, so 33 failure lines would say nothing 1 does not. */
static void test_matches_circuit(void) {
    printf("\nthe C Poseidon reproduces the circuit's own commitments\n");

    unsigned passed = 0;
    for (size_t i = 0; i < NUM_VECTORS; i++) {
        uint8_t out[32] = {0};
        char got[65] = {0};
        if (charra_poseidon_commit(VECTORS[i].path, VECTORS[i].path_len,
                    VECTORS[i].salt, out) != CHARRA_RC_SUCCESS) {
            printf("        (entry %zu: commit failed outright)\n", i);
            break;
        }
        to_hex(out, 32, got);
        if (strcmp(got, VECTORS[i].expect) != 0) {
            printf("        (first mismatch at entry %zu)\n", i);
            printf("           got     %s\n", got);
            printf("           circuit %s\n", VECTORS[i].expect);
            break;
        }
        passed++;
    }
    printf("        %u / %zu vectors matched\n", passed, NUM_VECTORS);
    check("every commitment the circuit produced is reproduced here",
            passed == NUM_VECTORS);
}

static void test_deterministic(void) {
    printf("\nsame path and salt always commit to the same value\n");

    uint8_t a[32] = {0}, b[32] = {0};
    charra_poseidon_commit(VECTORS[0].path, VECTORS[0].path_len,
            VECTORS[0].salt, a);
    charra_poseidon_commit(VECTORS[0].path, VECTORS[0].path_len,
            VECTORS[0].salt, b);
    /* The RP commits once and the circuit recomputes the same value; any
     * nondeterminism here makes every proof fail at random. */
    check("two calls agree", memcmp(a, b, sizeof(a)) == 0);
}

static void test_salt_changes_commitment(void) {
    printf("\nthe salt is load-bearing\n");

    uint8_t base[32] = {0}, flipped[32] = {0};
    uint8_t salt[32];
    memcpy(salt, VECTORS[0].salt, sizeof(salt));
    charra_poseidon_commit(
            VECTORS[0].path, VECTORS[0].path_len, salt, base);

    /* One bit. Without the salt mattering, an attacker enumerates the small
     * space of plausible system paths and reverses the whole log. */
    salt[31] ^= 0x01;
    charra_poseidon_commit(
            VECTORS[0].path, VECTORS[0].path_len, salt, flipped);
    check("one flipped salt bit changes the commitment",
            memcmp(base, flipped, sizeof(base)) != 0);

    /* And the same path under two different salts must not collide, which is
     * what stops a Verifier counting repeated paths. */
    uint8_t other[32] = {0};
    charra_poseidon_commit(VECTORS[1].path, VECTORS[1].path_len,
            VECTORS[0].salt, other);
    check("a different path under the same salt differs",
            memcmp(base, other, sizeof(base)) != 0);
}

static void test_path_len_is_committed(void) {
    printf("\npath_len is part of the commitment\n");

    /* The path is zero-padded before packing, so a path and the same path one
     * byte shorter pack to identical limbs. Only path_len separates them --
     * without it, "/etc/x\0" and "/etc/x" would collide. */
    uint8_t full[32] = {0}, short_[32] = {0};
    charra_poseidon_commit(
            VECTORS[0].path, VECTORS[0].path_len, VECTORS[0].salt, full);
    charra_poseidon_commit(
            VECTORS[0].path, VECTORS[0].path_len - 1, VECTORS[0].salt, short_);
    check("dropping the trailing NUL changes the commitment",
            memcmp(full, short_, sizeof(full)) != 0);
}

static void test_bad_arguments(void) {
    printf("\nbad arguments are rejected, not committed to\n");

    uint8_t out[32] = {0};
    check("NULL path rejected",
            charra_poseidon_commit(NULL, 4, VECTORS[0].salt, out) !=
                    CHARRA_RC_SUCCESS);
    check("NULL salt rejected",
            charra_poseidon_commit(VECTORS[0].path, VECTORS[0].path_len, NULL,
                    out) != CHARRA_RC_SUCCESS);
    check("NULL output rejected",
            charra_poseidon_commit(VECTORS[0].path, VECTORS[0].path_len,
                    VECTORS[0].salt, NULL) != CHARRA_RC_SUCCESS);
    /* A path longer than the circuit accepts cannot be committed at all --
     * silently truncating would produce a commitment the circuit rejects. */
    check("a path longer than the circuit accepts is rejected",
            charra_poseidon_commit(VECTORS[0].path,
                    CHARRA_POSEIDON_MAX_PATH + 1, VECTORS[0].salt, out) !=
                    CHARRA_RC_SUCCESS);
}

int main(void) {
    printf("Poseidon tests\n");
    printf("==============\n");

    test_matches_circuit();
    test_deterministic();
    test_salt_changes_commitment();
    test_path_len_is_committed();
    test_bad_arguments();

    printf("\n==============\n");
    printf("%u tests, %u failed\n", tests_run, tests_failed);

    if (tests_failed != 0) {
        printf("\nIf the vector check failed, the C and the circuit disagree.\n"
               "Every proof would fail, and the failure would surface only as\n"
               "an unsatisfiable circuit. Fix this before anything else.\n");
    }
    return (tests_failed == 0) ? 0 : 1;
}
