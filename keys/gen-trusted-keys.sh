#!/bin/sh
# Writes the trust anchor the roles read at runtime.
#
# bin/provision_trusted_keys reads public signing keys out of a TPM and
# writes them to keys/trusted_keys.txt. There is no CA and there are no
# certificates -- the file IS the trust decision, see
# src/core/charra_trusted_keys.h.
#
# TWO MODES, chosen by the environment:
#
#   Two TPMs (the normal setup) -- set ATTESTER_TCTI and RP_TCTI:
#       ATTESTER_TCTI="mssim:host=127.0.0.1,port=2321" \
#       RP_TCTI="mssim:host=127.0.0.1,port=2325" ./keys/gen-trusted-keys.sh
#     Each role's AK is read from ITS OWN TPM with --role, and the two
#     fragments are concatenated under one header.
#
#   One TPM (legacy/manual) -- set neither, and one run emits both
#     identities from whichever TPM $CHARRA_TCTI names.
#
# Why --role rather than running the tool twice without it: a run without
# --role emits BOTH identities from whichever TPM it is pointed at, so
# provisioning two TPMs that way would put a key the RP's own TPM can
# derive into the anchor labelled 'attester'. TPM2_Quote accepts a
# restricted key, so the RP could then produce a genuine hardware quote
# that satisfies the Verifier's Step 3b -- nothing forged, nothing to
# detect. One TPM, one role, one key.
#
# Re-run this whenever a TPM is reset: keys are derived from that TPM's
# hierarchy seed, so wiping an NVChip silently changes them and every
# signature check fails against a stale anchor -- as "untrusted identity",
# which reads like a rejected peer rather than a stale file.
#
# run_daemon.sh already calls this after resetting the TPMs.

set -e

OUT="trusted_keys.txt"

# Run from the repo root: the tool's default paths are repo-relative, the
# same way every role resolves keys/.
cd "$(dirname "$0")/.."

# Clean up partial output if anything below fails. A truncated anchor would
# read as "no identity is trusted" -- a far more confusing failure than the
# one that actually happened.
trap 'rm -f "keys/$OUT.tmp" "keys/$OUT.part"' EXIT

if [ ! -x bin/provision_trusted_keys ]; then
    echo "bin/provision_trusted_keys is missing -- run 'make provision_trusted_keys' first." >&2
    exit 1
fi

# Both or neither. One alone would silently provision a role against the
# wrong TPM, which produces an anchor that looks fine and rejects everyone.
if { [ -n "${ATTESTER_TCTI:-}" ] && [ -z "${RP_TCTI:-}" ]; } ||
   { [ -z "${ATTESTER_TCTI:-}" ] && [ -n "${RP_TCTI:-}" ]; }; then
    echo "Set BOTH ATTESTER_TCTI and RP_TCTI, or neither." >&2
    exit 1
fi

if [ -n "${ATTESTER_TCTI:-}" ]; then
    echo "Reading each role's AK from its own TPM ..."
    echo "  attester      <- $ATTESTER_TCTI"
    echo "  relying-party <- $RP_TCTI"

    cat > "keys/$OUT.tmp" <<'HEADER'
# CHARRA trust anchor -- generated by keys/gen-trusted-keys.sh, do not edit by hand.
#
# Every public key below is trusted unconditionally: a signing key is
# accepted if and only if it appears here. There are no certificates, no CA,
# no expiry and no revocation -- see src/core/charra_trusted_keys.h.
#
# Each role's key was read from that role's OWN TPM, and changes whenever
# that TPM's NVChip is wiped. Regenerate this file after any TPM reset.
HEADER

    CHARRA_TCTI="$ATTESTER_TCTI" ./bin/provision_trusted_keys \
        --role attester --out "keys/$OUT.part"
    cat "keys/$OUT.part" >> "keys/$OUT.tmp"

    CHARRA_TCTI="$RP_TCTI" ./bin/provision_trusted_keys \
        --role relying-party --out "keys/$OUT.part"
    cat "keys/$OUT.part" >> "keys/$OUT.tmp"

    rm -f "keys/$OUT.part"
else
    echo "Reading both roles' AKs from a single shared TPM ..."
    ./bin/provision_trusted_keys --out "keys/$OUT.tmp"
fi

# Published by rename so a reader never sees a half-written anchor.
mv "keys/$OUT.tmp" "keys/$OUT"

echo "Wrote keys/$OUT:"
grep -c 'BEGIN PUBLIC KEY' "keys/$OUT" | sed 's/^/  public keys: /'
